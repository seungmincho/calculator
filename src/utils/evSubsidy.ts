export function runningCost(o: { kmPerYear: number; years: number; evEff: number; chargeWon: number; iceEff: number; fuelWon: number }) {
  const km = o.kmPerYear * o.years
  const ev = o.evEff > 0 ? Math.round((km / o.evEff) * o.chargeWon) : 0
  const ice = o.iceEff > 0 ? Math.round((km / o.iceEff) * o.fuelWon) : 0
  return { ev, ice, saving: ice - ev }
}

