export type SizeClass = 'large' | 'small' // 중·대형 / 소형(경형 포함)

/** 차량 기본가격(만원) → 가격계수: 5,300 미만 100%, 8,500 미만 50%, 이상 0% */
export function priceFactor(priceMan: number): number {
  if (priceMan < 5300) return 1
  if (priceMan < 8500) return 0.5
  return 0
}

/** 부문별 상한 */
export const CAP = { large: 580, small: 530 } as const
const PERF_CAP = { large: 300, small: 250 } as const
const PERF_UNIT = { large: 150, small: 125 } as const // 연비·주행거리 보조금 규모별 금액
export const BASE_EFF = 5.0 // 기준가중연비 km/kWh
export const INCENTIVE_MAX = 280 // 배터리안전50 + 보급목표이행140 + 충전인프라40 + 혁신기술50

/** 가중값 = 상온×0.75 + 저온×0.25 (저온연비 = 저온주행거리/상온주행거리 × 상온연비) */
export function weighted(roomEff: number, roomRange: number, coldRange: number) {
  const coldEff = roomRange > 0 ? (coldRange / roomRange) * roomEff : 0
  return {
    eff: roomEff * 0.75 + coldEff * 0.25,
    range: roomRange * 0.75 + coldRange * 0.25,
  }
}

/** 주행거리계수 (별표1) */
export function rangeCoef(size: SizeClass, wRange: number): number {
  let c: number
  if (size === 'large') {
    if (wRange > 550) c = 1.21
    else if (wRange >= 440) c = 0.0019 * wRange + 0.164
    else c = 0.0054 * wRange - 1.376
  } else {
    c = wRange >= 300 ? 1.17 : 0.0033 * wRange + 0.175
  }
  return Math.max(0, c)
}

/** 등급 1~5 → 계수 1.0~0.6 (배터리효율·환경성), 사후관리 1~4 → 1.0~0.7 */
export const gradeCoef = (g: number) => Math.max(0.6, 1 - 0.1 * (Math.round(g) - 1))

export interface EstimateInput {
  size: SizeClass
  priceMan: number
  roomEff: number // 상온 복합전비 km/kWh
  roomRange: number // 상온 1회충전 주행거리 km
  coldRange: number // 저온 주행거리 km
  batteryGrade: number // 에너지밀도 등급 1~5
  envGrade: number // 재활용가치 등급 1~5
  asGrade: number // 사후관리 등급 1~4
  incentive: number // 배터리안전·보급목표이행·충전인프라·혁신기술 합계(만원)
}

/** 성능 기반 국비 추정 (별표1). 경형은 배터리 계수 미적용이지만 여기선 등급 1 입력으로 표현 */
export function estimateNational(i: EstimateInput) {
  const w = weighted(i.roomEff, i.roomRange, i.coldRange)
  const effCoef = w.eff / BASE_EFF
  const rCoef = rangeCoef(i.size, w.range)
  const perf = Math.min(PERF_CAP[i.size], PERF_UNIT[i.size] * effCoef + PERF_UNIT[i.size] * rCoef)
  const coef = gradeCoef(i.batteryGrade) * gradeCoef(i.envGrade) * gradeCoef(i.asGrade)
  const incentive = Math.min(INCENTIVE_MAX, Math.max(0, i.incentive))
  // ponytail: 배터리안전보조금을 성능보조금과 함께 계수에 곱하는 부분은 incentive에 뭉쳐 계수 미적용 — 최대 50만원×(1-계수) 오차
  const beforePrice = Math.min(CAP[i.size], perf * coef + incentive)
  const pf = priceFactor(i.priceMan)
  return {
    wEff: w.eff, wRange: w.range, effCoef, rangeCoef: rCoef, perf, coef, priceFactor: pf,
    national: Math.round(beforePrice * pf),
  }
}

// ── 구매자 추가지원 (4-1-2) ──
/** 전환지원금 국비: 일반 국비 0~500 구간 비례, 500 이상 100 */
export const conversionNational = (national: number) => Math.round(100 * Math.min(1, Math.max(0, national) / 500))
export const multiChildBonus = (children: number) => (children >= 4 ? 300 : children === 3 ? 200 : children === 2 ? 100 : 0)

export interface Buyer {
  conversion: boolean // 출고·보유 3년 이상 내연차 판매/폐차
  youth: boolean // 19~34세 생애 첫차
  lowIncome: boolean // 차상위 이하
  children: number // 18세 이하 자녀 수
}

export interface SubsidyInput {
  priceMan: number
  discountMan: number // 제조사 할인
  national: number // 국비(가격계수 반영 후)
  local: number // 지방비
  convLocalRatio: number // 전환지원금 지방비 비율 (대부분 0.3)
  buyer: Buyer
  light: boolean // 경차(취득세 4%)
}

export interface SubsidyResult {
  national: number
  local: number
  convNational: number
  convLocal: number
  youth: number
  lowIncome: number
  multiChild: number
  extras: number
  total: number
  netPrice: number // 만원
  acqTax: number // 원 (감면 전)
  acqRelief: number // 원
  acqPay: number // 원
}

export const ACQ_RELIEF_CAP = 1_400_000 // 2026.12.31까지 (2027년부터 70만원 개정안 입법예고 중)

/** 취득세: 과세표준 = 공급가액(부가세 제외) = (가격-할인)/1.1, 비영업용 승용 7%(경차 4%) */
export function acquisitionTax(priceMan: number, discountMan: number, light: boolean) {
  const base = Math.max(0, priceMan - discountMan) * 10_000 / 1.1
  const tax = Math.floor((base * (light ? 0.04 : 0.07)) / 10) * 10
  const relief = Math.min(tax, ACQ_RELIEF_CAP)
  return { tax, relief, pay: tax - relief }
}

export function calcSubsidy(i: SubsidyInput): SubsidyResult {
  const national = Math.max(0, Math.round(i.national))
  const local = Math.max(0, Math.round(i.local))
  const b = i.buyer
  const convNational = b.conversion ? conversionNational(national) : 0
  const convLocal = b.conversion ? Math.round(convNational * i.convLocalRatio) : 0
  // 비율 추가지원은 '국비 지원액의 20%'가 총액(국비·지방비가 나눠 부담) — 지침 계산 예시 500×20%=100
  const youth = b.youth ? Math.round(national * 0.2) : 0
  const lowIncome = b.lowIncome ? Math.round(national * 0.2) : 0
  const multiChild = multiChildBonus(b.children)
  const extras = convNational + convLocal + youth + lowIncome + multiChild
  const total = national + local + extras
  const netPrice = Math.max(0, i.priceMan - i.discountMan - total)
  const acq = acquisitionTax(i.priceMan, i.discountMan, i.light)
  return {
    national, local, convNational, convLocal, youth, lowIncome, multiChild, extras, total, netPrice,
    acqTax: acq.tax, acqRelief: acq.relief, acqPay: acq.pay,
  }
}

