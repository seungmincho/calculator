export const REGIONS: Region[] = RAW.split('\n').map((line) => {
  const [cd, sido, name, ratio, convRatio, vals] = line.split('|')
  return {
    cd, sido, name, ratio: Number(ratio), convRatio: Number(convRatio),
    local: vals.split(',').map((v) => (v === '' ? null : Number(v))),
  }
})

export const SIDOS = [...new Set(REGIONS.map((r) => r.sido))]
export const regionByCd = (cd: string) => REGIONS.find((r) => r.cd === cd)

/** 모델의 지방비: 공고 금액 있으면 그대로(exact), 없으면 null */
export function localFor(region: Region, modelId: string): number | null {
  const idx = MODELS.findIndex((m) => m.id === modelId)
  return idx < 0 ? null : region.local[idx] ?? null
}

/** 목록에 없는 차: 지자체 중앙 비율로 추정 */
export const estimateLocal = (region: Region, national: number) => Math.round(national * region.ratio)
