interface Line { text: string; to: Recipient[] | null }

function parse(s: string): Line {
  const m = /^([bckfpt]+)\|(.*)$/.exec(s)
  return m ? { text: m[2], to: m[1].split('').map((c) => CODE[c]) } : { text: s, to: null }
}

function lines(arr: string[], r: Recipient): string[] {
  return arr.map(parse).filter((l) => !l.to || l.to.includes(r)).map((l) => l.text)
}

/** 문장의 마지막 어절 (구두점 제외) — 한 문구 안에서 같은 끝맺음이 반복되면 어색해서 거른다 */
const lastWord = (s: string) => s.replace(/[.!?]+$/, '').split(' ').pop() ?? ''
export const sentences = (s: string) => s.replace(/([.!?])\s+/g, '$1\n').split('\n').filter(Boolean)

function repetitive(parts: string[]): boolean {
  const seen = new Set<string>()
  for (const p of parts) {
    for (const s of sentences(p)) {
      if (s.startsWith('다시 한번')) continue // '다시 한번 축하드립니다'는 일부러 되풀이하는 말
      const w = lastWord(s)
      if (seen.has(w)) return true
      seen.add(w)
    }
  }
  return false
}

/** 받는 사람·말투에 맞는 모든 문장 조합 (인덱스 순서 고정) */
export function combos(situation: Situation, recipient: Recipient, tone: Tone, length: Length): string[][] {
  const pool = DATA[situation][tone]
  const open = lines(pool.open, recipient)
  const mid = lines(pool.mid, recipient)
  const wish = lines(pool.wish, recipient)
  const close = lines(pool.close, recipient).filter((c) => length !== 'short' || !c.startsWith('다시 한번'))
  const out: string[][] = []
  for (const o of open) for (const c of close) {
    if (length === 'short') out.push([o, c])
    else for (const m of mid) {
      if (length === 'medium') out.push([o, m, c])
      else for (const w of wish) out.push([o, m, w, c])
    }
  }
  return out.filter((parts) => !repetitive(parts))
}

/** mulberry32 */
function rng(seed: number) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function fill(s: string, situation: Situation, ctx: DateCtx | null): string {
  const gjYear = situation === 'seollal' ? ctx?.seollal?.year : ctx?.newYear
  return s
    .replace('{yr}', ctx ? `${ctx.yearEnd}년` : '올해')
    .replace('{ny}', ctx ? `${ctx.newYear}년` : '새해')
    .replace('{gj}', gjYear ? `${ganji(gjYear)}년 ` : '')
    .replace('{seol}', ctx?.seollal?.from ? `${ctx.seollal.from}부터 시작되는 ` : '')
    .replace('{chu}', ctx?.chuseok?.from ? `${ctx.chuseok.from}부터 시작되는 ` : '')
}

const hasBatchim = (s: string) => {
  const c = s.charCodeAt(s.length - 1) - 0xac00
  return c >= 0 && c <= 11171 && c % 28 !== 0
}

/** 부르는 말: 친구 반말이면 '민수야/지은아', 윗사람·거래처는 '님'이 없으면 붙임 */
export function vocative(name: string, recipient: Recipient, tone: Tone): string {
  const n = name.trim()
  if (!n) return ''
  const hangulEnd = /[가-힣]$/.test(n)
  if (tone === 'casual' && recipient === 'friend' && hangulEnd && !/(님|씨)$/.test(n)) return n + (hasBatchim(n) ? '아' : '야')
  if (tone !== 'casual' && ['boss', 'client', 'teacher'].includes(recipient) && hangulEnd && !/(님|씨)$/.test(n)) return n + '님'
  return n
}

export function signature(sender: string, recipient: Recipient, tone: Tone): string {
  const s = sender.trim()
  if (!s) return ''
  if (tone === 'casual') return `- ${s}`
  return `${s} ${tone === 'formal' && ['boss', 'teacher', 'family'].includes(recipient) ? '올림' : '드림'}`
}

function addEmoji(s: string, e: string): string {
  return /[.]$/.test(s) ? `${s.slice(0, -1)} ${e}` : `${s} ${e}`
}

/** 조합 하나를 완성된 문구로 */
export function render(parts: string[], o: Options, ctx: DateCtx | null, i = 0): string {
  let p = parts.map((s) => fill(s, o.situation, ctx))
  if (o.emoji) {
    const em = EMOJI[o.situation]
    p = p.map((s, k) => (k === 0 ? addEmoji(s, em[i % em.length]) : k === p.length - 1 ? addEmoji(s, em[(i + 1) % em.length]) : s))
  }
  const voc = vocative(o.name ?? '', o.recipient, o.tone)
  if (voc) p[0] = `${voc}, ${p[0]}`
  const body = p.length > 2 ? [p[0], p.slice(1, -1).join(' '), p[p.length - 1]] : p
  const sig = signature(o.sender ?? '', o.recipient, o.tone)
  return body.join('\n') + (sig ? `\n\n${sig}` : '')
}

/** 시드로 섞어 count개. 같은 옵션+시드면 같은 결과. 첫 문장이 겹치지 않게 먼저 고른다 */
export function generate(o: Options, ctx: DateCtx | null, count = 6): string[] {
  const all = combos(o.situation, o.recipient, o.tone, o.length)
  const rand = rng(o.seed * 2654435761 + 1)
  for (let i = all.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    ;[all[i], all[j]] = [all[j], all[i]]
  }
  // 카드끼리 같은 문장이 덜 겹치게: 이미 쓴 문장 횟수 합이 가장 적은 조합부터 (동점이면 섞인 순서)
  const picked: string[][] = []
  const used = new Map<string, number>()
  while (picked.length < Math.min(count, all.length)) {
    let best: string[] | null = null
    let bestScore = Infinity
    for (const c of all) {
      if (picked.includes(c)) continue
      const sc = c.reduce((n, s) => n + (used.get(s) ?? 0), 0)
      if (sc < bestScore) { best = c; bestScore = sc; if (sc === 0) break }
    }
    picked.push(best!)
    best!.forEach((s) => used.set(s, (used.get(s) ?? 0) + 1))
  }
  return picked.map((c, i) => render(c, o, ctx, i))
}

/** 문자 바이트(한글 2·영문 1)와 종류. 90바이트 넘거나 이모지가 있으면 LMS */
export function smsInfo(s: string): { chars: number; bytes: number; type: 'SMS' | 'LMS' } {
  let bytes = 0
  let emoji = false
  const chars = Array.from(s)
  for (const ch of chars) {
    const cp = ch.codePointAt(0) ?? 0
    if (cp > 0xffff || (cp >= 0x2600 && cp <= 0x27bf)) emoji = true
    bytes += cp < 128 ? 1 : 2
  }
  return { chars: chars.length, bytes, type: bytes <= 90 && !emoji ? 'SMS' : 'LMS' }
}
