export const DEFAULT_GRADE: Record<Track, number> = { general: 9, police: 10, teacher: 1 }
export const DEFAULT_STEP: Record<Track, number> = { general: 1, police: 1, teacher: 9 }

const cut10 = (n: number) => Math.floor(n / 10 + 1e-9) * 10

/** g = 별표 열 번호(1부터), 그 직급의 최고 호봉 */
export const maxStep = (track: Track, g: number) => PAY_2026[track][g - 1]?.length ?? 0
/** 2027 추정 봉급: 2026 × 1.039, 100원 단위 반올림(정수 연산) */
export const est2027 = (v: number) => Math.round((v * (1000 + RAISE_2027_PERMIL)) / 100_000) * 100
export const basePay = (track: Track, g: number, step: number, year: InsuranceYear = 2026) => {
  const v = PAY_2026[track][g - 1][step - 1]
  return year === 2027 ? est2027(v) : v
}

export interface CivilPayInput {
  track: Track
  g: number
  step: number
  family: number // 공제대상가족 수(본인 포함)
  children: number // 그중 8~20세 자녀
  allowances: boolean // 정액급식비·직급보조비 포함
}

/** 월 실수령액. year = 2027 이면 추정 봉급과 2027 건보·장기요양 요율(소득세는 현행 간이세액표). 수당은 2026 금액. */
export function calcCivilPay(x: CivilPayInput, year: InsuranceYear = 2026) {
  const pay = basePay(x.track, x.g, x.step, year)
  const meal = x.allowances ? MEAL : 0
  const gradeAllowance = x.allowances ? GRADE_ALLOWANCE[x.track][x.g - 1] : 0
  const gross = pay + meal + gradeAllowance
  const taxable = gross - Math.min(meal, MEAL_TAX_FREE)
  const pension = cut10((taxable * PENSION_PCT) / 100)
  const ins = fourInsurance(taxable, year, 'under150', 0)!
  const health = ins.rows.health.employee
  const ltc = ins.rows.ltc.employee
  const incomeTax = wageTax(taxable, x.family, x.children)
  const localTax = cut10(incomeTax / 10)
  const deductions = pension + health + ltc + incomeTax + localTax
  return { year, pay, meal, gradeAllowance, gross, taxable, pension, health, ltc, incomeTax, localTax, deductions, net: gross - deductions }
}
export type CivilPayResult = ReturnType<typeof calcCivilPay>
