// 퍼센트 계산기 회귀 체크: node scripts/check-percent.ts
import assert from 'node:assert/strict'
import {
  clean, round, parseNum, percentOf, ratio, change, discount, originalPrice, chainRate, vatSplit, fmt, fmtKo, parseQuery,
} from '../src/utils/percent.ts'

// 부동소수
assert.equal(clean(0.1 + 0.2), 0.3)
assert.equal(round(1.005, 2), 1.01)
assert.equal(round(-1.005, 2), -1.01)
assert.equal(round(2.5, 0), 3)
assert.equal(round(-0.0001, 2), 0)
assert.equal(round(1e-7, 2), 0)
assert.equal(round(1e21, 2), 1e21)
assert.equal(percentOf(0.1, 30), 0.03)          // 0.1*30/100 = 0.030000000000000002
assert.equal(percentOf(19.99, 15), 2.9985)

// 숫자 해석
assert.equal(parseNum(''), null)
assert.equal(parseNum('  '), null)
assert.equal(parseNum('abc'), null)
assert.equal(parseNum('1.2.3'), null)
assert.equal(parseNum('12,000'), 12000)
assert.equal(parseNum('5만'), 50000)
assert.equal(parseNum('5만원'), 50000)
assert.equal(parseNum('3.5만'), 35000)
assert.equal(parseNum('1억 2천만'), 120_000_000)
assert.equal(parseNum('1억2345만6789'), 123_456_789)
assert.equal(parseNum('5천'), 5000)
assert.equal(parseNum('천만'), 10_000_000)
assert.equal(parseNum('1만 5000'), 15000)
assert.equal(parseNum('-3'), -3)
assert.equal(parseNum('−3.5'), -3.5)
assert.equal(parseNum('15%'), 15)
assert.equal(parseNum('.5'), 0.5)
assert.equal(parseNum('0'), 0)
assert.equal(parseNum('1e3'), 1000)
assert.equal(parseNum('2 3'), 23)  // 공백은 무시 (타이핑 중 "2 3")

// 계산
assert.equal(percentOf(50000, 15), 7500)
assert.equal(percentOf(-200, 15), -30)
assert.equal(ratio(300, 1200), 25)
assert.equal(ratio(1, 0), null)
assert.equal(ratio(0, 5), 0)
assert.equal(round(ratio(1, 3)!, 2), 33.33)
assert.equal(change(30000, 40000).diff, 10000)
assert.equal(round(change(30000, 40000).pct!, 2), 33.33)
assert.deepEqual(change(100, 80), { diff: -20, pct: -20 })
assert.deepEqual(change(0, 5), { diff: 5, pct: null })
assert.deepEqual(change(-100, -50), { diff: 50, pct: 50 })   // 적자 축소 = 개선(+)
assert.deepEqual(change(-100, 50), { diff: 150, pct: 150 })
assert.deepEqual(discount(89000, 30), { off: 26700, sale: 62300 })
assert.deepEqual(discount(19900, 15), { off: 2985, sale: 16915 })
assert.equal(originalPrice(62300, 30), 89000)
assert.equal(originalPrice(70000, 30), 100000)
assert.equal(originalPrice(1, 100), null)
assert.equal(originalPrice(1, 120), null)
assert.equal(chainRate([30, 20]), 44)
assert.equal(chainRate([20, 10]), 28)
assert.equal(chainRate([]), 0)
assert.equal(chainRate([100, 50]), 100)
assert.deepEqual(vatSplit(110000), { supply: 100000, vat: 10000 })
assert.equal(round(vatSplit(10000).supply, 2), 9090.91)

// 표시
assert.equal(fmt(7500, 2), '7,500')
assert.equal(fmt(33.3333, 2), '33.33')
assert.equal(fmt(0.1 + 0.2, 4), '0.3')
assert.equal(fmt(-0.0001, 2), '0')
assert.equal(fmtKo(123_456_789, 0), '1억 2,345만 6,789')
assert.equal(fmtKo(100_000_000, 0), '1억')
assert.equal(fmtKo(50000, 0), '5만')
assert.equal(fmtKo(9999, 0), '9,999')
assert.equal(fmtKo(-35000, 0), '-3만 5,000')
assert.equal(fmtKo(12345.678, 2), '1만 2,345.68')
assert.equal(fmtKo(10000.5, 1), '1만 0.5')
assert.equal(fmtKo(1.5e12, 0), '1조 5,000억')

// 한 줄 입력
assert.deepEqual(parseQuery('5만원의 15%'), { kind: 'of', a: 50000, p: 15 })
assert.deepEqual(parseQuery('50000의 15%는?'), { kind: 'of', a: 50000, p: 15 })
assert.deepEqual(parseQuery('15% of 200'), { kind: 'of', a: 200, p: 15 })
assert.deepEqual(parseQuery('50000 x 15%'), { kind: 'of', a: 50000, p: 15 })
assert.deepEqual(parseQuery('3만→4만'), { kind: 'change', from: 30000, to: 40000 })
assert.deepEqual(parseQuery('3만 -> 4만'), { kind: 'change', from: 30000, to: 40000 })
assert.deepEqual(parseQuery('3만에서 4만으로'), { kind: 'change', from: 30000, to: 40000 })
assert.deepEqual(parseQuery('1억 2천만 → 1억 5천만'), { kind: 'change', from: 120_000_000, to: 150_000_000 })
assert.deepEqual(parseQuery('300은 1200의 몇 %?'), { kind: 'ratio', part: 300, whole: 1200 })
assert.deepEqual(parseQuery('45/60'), { kind: 'ratio', part: 45, whole: 60 })
assert.deepEqual(parseQuery('12만 30% 할인'), { kind: 'discount', price: 120000, rate: 30 })
assert.deepEqual(parseQuery('12만원에서 30퍼센트 세일'), { kind: 'discount', price: 120000, rate: 30 })
assert.deepEqual(parseQuery('30% 할인해서 7만이면'), { kind: 'reverse', sale: 70000, rate: 30 })
assert.deepEqual(parseQuery('7만 30% 할인된 가격의 정가'), { kind: 'reverse', sale: 70000, rate: 30 })
assert.equal(parseQuery(''), null)
assert.equal(parseQuery('안녕하세요'), null)
assert.equal(parseQuery('5만원의'), null)

console.log('check-percent: OK')
