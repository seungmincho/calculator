import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir,writeFile } from 'node:fs/promises'
const base=process.argv[2]??'http://127.0.0.1:8790'
const dir='.wrangler/everland-replan/evidence'
await mkdir(dir,{recursive:true})
const response=await fetch(`${base}/everland/`),html=await response.text()
assert.equal(response.status,200)
assert.ok(html.includes('everland-result'),'recommendation is in server HTML')
assert.ok(html.includes('이 날짜를 추천하는 이유'))
assert.ok(!html.includes('name="robots" content="noindex"'))
const payload=JSON.parse(html.match(/<script id="everland-data" type="application\/json">(.*?)<\/script>/s)[1])
assert.ok(payload.forecast.slots.length>20)
const browser=await chromium.launch({headless:true})
const context=await browser.newContext({viewport:{width:1280,height:960},serviceWorkers:'block'})
const page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
try {
 await page.goto(`${base}/everland/`,{waitUntil:'networkidle'})
 assert.equal(await page.locator('h1').count(),1)
 await page.getByRole('button',{name:'아이와 함께',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:'아이와 함께',exact:true}).getAttribute('aria-pressed'),'true')
 assert.ok(page.url().includes('profile=family'))
 await page.getByRole('button',{name:'주말·공휴일만',exact:true}).click()
 const weekendDates=page.getByRole('group',{name:'날짜별로 비교하기'}).getByRole('button')
 for(const text of await weekendDates.allTextContents()) assert.match(text,/토|일/)
 await page.getByRole('button',{name:'평일 포함',exact:true}).click()
 await page.getByRole('group',{name:'날짜별로 비교하기'}).getByRole('button').last().click()
 const selected=await page.locator('#everland-date-detail h2').innerText()
 await page.reload({waitUntil:'networkidle'})
 assert.equal(await page.locator('#everland-date-detail h2').innerText(),selected,'shared URL restores selection')
 const detailUrl=await page.getByRole('link',{name:'이 날짜의 예보 페이지'}).getAttribute('href')
 const detailResponse=await context.request.get(base+detailUrl)
 assert.equal(detailResponse.status(),200)
 assert.ok((await detailResponse.text()).includes('rel="canonical" href="https://toolhub.ai.kr/everland/date/'))
 await page.goto(`${base}/everland/`,{waitUntil:'networkidle'})
 const downloadPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'이미지 저장',exact:true}).click()
 const download=await downloadPromise
 await download.saveAs(`${dir}/shared-result.png`)
 await page.screenshot({path:`${dir}/desktop.png`,fullPage:true})
 for(const width of [390,320]) {
  await page.setViewportSize({width,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`no page overflow at ${width}`)
  if(width===390) {await page.screenshot({path:`${dir}/mobile.png`,fullPage:true});await page.screenshot({path:`${dir}/mobile-fold.png`})}
 }
 await page.setViewportSize({width:1280,height:960})
 await page.goto(`${base}/everland/map/`,{waitUntil:'networkidle'})
 const frame=page.frameLocator('#everland-map-frame')
 await frame.locator('.map img').waitFor()
 assert.equal(await frame.locator('.map img').evaluate(img=>img.complete&&img.naturalWidth>1000),true,'real guide image loaded')
 assert.equal(await frame.locator('.pin').count(),39)
 assert.equal(await frame.locator('.pin:visible').count(),8,'overview avoids overlapping all 39 pins')
 await frame.locator('#search').fill('T 익스프레스')
 assert.equal(await frame.locator('.pin:visible').count(),1)
 await frame.locator('.pin:visible').click()
 assert.match(await frame.locator('#selected').innerText(),/T 익스프레스/)
 await frame.locator('#search').fill('')
 await frame.locator('#zoom-in').click()
 assert.equal(await frame.locator('#map').evaluate(el=>el.style.width),'150%')
 assert.equal(await frame.locator('.pin:visible').count(),39,'zoom reveals every matched facility')
 await frame.locator('#zoom-reset').click()
 await page.screenshot({path:`${dir}/map-desktop.png`,fullPage:true})
 await page.setViewportSize({width:390,height:844})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 await page.screenshot({path:`${dir}/map-mobile.png`,fullPage:true})
 await page.screenshot({path:`${dir}/map-mobile-fold.png`})
 const sitemap=await context.request.get(`${base}/everland/sitemap.xml`)
 assert.equal(sitemap.status(),200)
 assert.ok((await sitemap.text()).includes('/everland/date/'))
 const old=await context.request.get(`${base}/everland-wait-times/`,{maxRedirects:0})
 assert.equal(old.status(),301)
 assert.equal(old.headers().location,'/everland/map/')
 assert.deepEqual(errors,[])
 const result={base,ssr:true,profiles:true,weekends:true,urlRestore:true,datePages:true,mapPins:39,mapImage:true,zoom:true,mobile:[390,320],sitemap:true,redirect:true,errors}
 await writeFile(`${dir}/results.json`,JSON.stringify(result,null,2))
 console.log(JSON.stringify(result))
} finally {await browser.close()}
